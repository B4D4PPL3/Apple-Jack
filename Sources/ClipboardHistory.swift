import AppKit
import ImageIO

// Capture only standard representations; never archive arbitrary pasteboard data.
enum ClipboardCapture {
    static let ignored = Set(["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"])
    static func read(_ board: NSPasteboard, source: String, date: Date = Date()) throws -> ClipboardEntry? {
        let before = board.changeCount
        guard Set((board.types ?? []).map(\.rawValue)).isDisjoint(with: ignored) else { return nil }
        guard let values = board.pasteboardItems, !values.isEmpty, values.count <= 50 else { return nil }
        guard values.allSatisfy({ Set($0.types.map(\.rawValue)).isDisjoint(with: ignored) }) else { return nil }
        var result: ClipboardEntry?
        if values.contains(where: { $0.types.contains(.fileURL) }) {
            let files = values.compactMap { item -> [String: Data]? in
                guard let text = item.string(forType: .fileURL), let url = URL(string: text), url.isFileURL else { return nil }
                return [NSPasteboard.PasteboardType.fileURL.rawValue: Data(url.absoluteString.utf8)]
            }
            guard files.count == values.count else { return nil }
            let paths = files.compactMap { $0[NSPasteboard.PasteboardType.fileURL.rawValue].flatMap { String(data: $0, encoding: .utf8) }.flatMap(URL.init(string:))?.path }
            result = .make(kind: .files, text: paths.joined(separator: "\n"), items: files, source: source, date: date)
        } else if let text = board.string(forType: .string) ?? board.string(forType: .URL), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard text.utf8.count <= 1_048_576 else { throw ClipboardFailure(message: "Skipped text larger than 1 MB.") }
            var formats = [NSPasteboard.PasteboardType.string.rawValue: Data(text.utf8)]
            if values.count == 1 {
                for type in [NSPasteboard.PasteboardType.rtf, .html, .URL] where values[0].types.contains(type) {
                    if let data = values[0].data(forType: type), data.count <= 2_097_152 { formats[type.rawValue] = data }
                }
            }
            result = .make(kind: .text, text: text, items: [formats], source: source, date: date)
        } else if let item = values.first, values.count == 1 {
            for type in [NSPasteboard.PasteboardType.png, .tiff] where item.types.contains(type) {
                guard let data = item.data(forType: type) else { continue }
                guard data.count <= 8_388_608 else { throw ClipboardFailure(message: "Skipped image larger than 8 MB.") }
                guard let image = CGImageSourceCreateWithData(data as CFData, nil), CGImageSourceGetCount(image) > 0 else { return nil }
                result = .make(kind: .image, text: "", items: [[type.rawValue: data]], source: source, date: date)
                break
            }
        }
        guard before == board.changeCount else { return nil }
        return result
    }
    static func thumbnail(_ entry: ClipboardEntry) -> NSImage? {
        // Called by the preview worker. Finder puts file URLs on the clipboard,
        // not image bytes. Decode a thumbnail without changing that payload.
        switch entry.kind {
        case .image:
            guard let data = entry.items.first?[NSPasteboard.PasteboardType.png.rawValue] ?? entry.items.first?[NSPasteboard.PasteboardType.tiff.rawValue] else { return nil }
            return thumbnail(CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary), maxPixels: 720)
        case .files:
            guard entry.fileURLs.count == 1, let url = entry.fileURLs.first else { return nil }
            return fileThumbnail(url, maxPixels: 720)
        case .text:
            return nil
        }
    }

    static func fileThumbnail(_ url: URL, maxPixels: Int, maxBytes: Int? = 67_108_864) -> NSImage? {
        guard let values = try? url.resourceValues(forKeys: [.isRegularFileKey, .fileSizeKey, .volumeIsLocalKey, .isUbiquitousItemKey, .ubiquitousItemDownloadingStatusKey]),
              values.isRegularFile == true, values.volumeIsLocal == true,
              let size = values.fileSize, size > 0, maxBytes.map({ size <= $0 }) ?? true else { return nil }
        if values.isUbiquitousItem == true && values.ubiquitousItemDownloadingStatus == .notDownloaded { return nil }
        let source = CGImageSourceCreateWithURL(url as CFURL, [kCGImageSourceShouldCache: false] as CFDictionary)
        return thumbnail(source, maxPixels: maxPixels)
    }

    private static func thumbnail(_ source: CGImageSource?, maxPixels: Int) -> NSImage? {
        guard let source, CGImageSourceGetCount(source) > 0,
              let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [kCGImageSourceCreateThumbnailFromImageAlways: true,
                    kCGImageSourceThumbnailMaxPixelSize: maxPixels, kCGImageSourceCreateThumbnailWithTransform: true,
                    kCGImageSourceShouldCacheImmediately: true] as CFDictionary) else { return nil }
        return NSImage(cgImage: image, size: NSSize(width: image.width, height: image.height))
    }
    static func write(_ entry: ClipboardEntry, to board: NSPasteboard, plainText: Bool = false) throws -> Int {
        guard ClipboardArchive.valid(entry) else { throw ClipboardFailure(message: "This clipboard item is invalid.") }
        let payload: [[String: Data]]
        if plainText {
            guard let text = entry.textRepresentation else {
                throw ClipboardFailure(message: "This image has no file path or text to copy. Use Copy to copy the image.")
            }
            payload = [[NSPasteboard.PasteboardType.string.rawValue: Data(text.utf8)]]
        } else {
            if entry.kind == .files, !entry.fileURLs.allSatisfy({ FileManager.default.fileExists(atPath: $0.path) }) {
                throw ClipboardFailure(message: "A referenced file has moved or is unavailable. The clipboard has not changed.")
            }
            payload = entry.items
        }
        let items = payload.map { formats -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (key, data) in formats { item.setData(data, forType: .init(key)) }
            return item
        }
        board.clearContents()
        guard board.writeObjects(items) else { throw ClipboardFailure(message: "macOS could not copy this item. Try Copy again.") }
        return board.changeCount
    }
}

final class ClipboardHistory {
    static let enabledKey = "clipboardHistoryEnabled"
    private let defaults: UserDefaults
    private let board: NSPasteboard
    private let directory: URL
    private let queue = DispatchQueue(label: "com.fonz.applejack.clipboard", qos: .utility)
    private var archive: ClipboardArchive? // worker queue only
    private var lastChange = 0 // worker queue only
    private var timer: Timer?
    private var polling = false // main thread only
    private let lock = NSLock()
    private var generation = 0
    private(set) var entries: [ClipboardEntry] = []
    private(set) var status = ""
    private(set) var ready = false
    var didChange: (() -> Void)?
    var enabled: Bool { defaults.bool(forKey: Self.enabledKey) }
    init(defaults: UserDefaults = .standard, board: NSPasteboard = .general, directory: URL? = nil) {
        self.defaults = defaults; self.board = board
        self.directory = directory ?? FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Library/Application Support/Apple Jack Public/Clipboard", isDirectory: true)
    }
    private func epoch() -> Int { lock.lock(); defer { lock.unlock() }; return generation }
    private func invalidateCapture() { lock.lock(); generation += 1; lock.unlock() }
    func start() {
        guard timer == nil else { return }
        queue.async { [weak self] in
            guard let self else { return }
            do {
                self.archive = try ClipboardArchive(directory: self.directory)
                self.lastChange = self.board.changeCount
                self.publish(status: "", ready: true)
            } catch { self.publish(status: "Couldn’t load clipboard history: \(error.localizedDescription)", ready: false) }
        }
        let timer = Timer(timeInterval: 0.8, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common); self.timer = timer
    }
    func stop() { timer?.invalidate(); timer = nil; invalidateCapture() }
    func setEnabled(_ enabled: Bool) {
        invalidateCapture()
        defaults.set(enabled, forKey: Self.enabledKey)
        // Resume starts with future copies, never captures a copy made while paused.
        queue.async { [weak self] in guard let self else { return }; self.lastChange = self.board.changeCount }
        status = ""; didChange?()
    }
    func poll() {
        guard enabled, ready, !polling else { return }
        polling = true
        let token = epoch()
        let source = String((NSWorkspace.shared.frontmostApplication?.localizedName ?? "Mac").prefix(256))
        queue.async { [weak self] in
            guard let self else { return }
            defer { DispatchQueue.main.async { self.polling = false } }
            guard token == self.epoch(), let archive = self.archive else { return }
            if #available(macOS 15.4, *) {
                if self.board.accessBehavior == .alwaysDeny || self.board.accessBehavior == .ask {
                    self.publish(status: "Clipboard access is restricted. Allow Apple Jack in System Settings → Privacy & Security → Paste from Other Apps, then copy something new.")
                    return
                }
            }
            let change = self.board.changeCount
            guard change != self.lastChange else { return }
            do {
                let entry = try ClipboardCapture.read(self.board, source: source)
                guard token == self.epoch() else { return }
                guard self.board.changeCount == change else { return }
                self.lastChange = change
                if let entry { try archive.add(entry); self.publish(status: "") }
            } catch {
                guard token == self.epoch() else { return }
                self.lastChange = change
                self.publish(status: error.localizedDescription)
            }
        }
    }
    private func publish(status: String, ready: Bool? = nil) {
        let snapshot = archive?.entries ?? []
        DispatchQueue.main.async { [weak self] in
            guard let self else { return }
            self.entries = snapshot; self.status = status
            if let ready { self.ready = ready }
            self.didChange?()
        }
    }
    func copy(_ entry: ClipboardEntry, plainText: Bool = false, completion: @escaping (Bool) -> Void) {
        queue.async { [weak self] in
            guard let self else { return }
            do {
                self.lastChange = try ClipboardCapture.write(entry, to: self.board, plainText: plainText)
                self.publish(status: "Copied. Switch to your app and press ⌘V to paste.")
                DispatchQueue.main.async { completion(true) }
            } catch {
                self.publish(status: error.localizedDescription)
                DispatchQueue.main.async { completion(false) }
            }
        }
    }
    func refreshExpiry() { mutate { try $0.expire() } }
    func togglePin(_ id: UUID) { mutate { try $0.togglePin(id) } }
    func remove(_ id: UUID) { mutate { try $0.remove(id) } }
    func clear(keepPinned: Bool) {
        invalidateCapture()
        mutate { [weak self] archive in
            try archive.clear(keepPinned: keepPinned)
            if let self { self.lastChange = self.board.changeCount }
        }
    }
    private func mutate(_ change: @escaping (ClipboardArchive) throws -> Void) {
        queue.async { [weak self] in
            guard let self, let archive = self.archive else { return }
            do { try change(archive); self.publish(status: "") }
            catch { self.publish(status: error.localizedDescription) }
        }
    }
    deinit { timer?.invalidate() }
}
